HEADER = f"""# Generated by Manim Studio {__version__}
# Render with: manim -pql <this file> Szene1
from manim import *
import numpy as np
"""


def scene_with(*objects, steps=()) -> Scene:
    return Scene(id="scene1", name="Szene 1", objects=list(objects), steps=list(steps))


def script_for(scene: Scene, **options) -> str:
    return generate_script(make_project(scene), CodegenOptions(**options))


def construct_lines(script: str) -> list[str]:
    """Return the stripped, non-empty lines inside ``construct``."""
    body = script.split("def construct(self):", 1)[1]
    return [line.strip() for line in body.splitlines() if line.strip()]


def flat(script: str) -> str:
    """Join wrapped calls into single lines for substring checks."""
    return " ".join(construct_lines(script)).replace("( ", "(").replace(", )", ")")


