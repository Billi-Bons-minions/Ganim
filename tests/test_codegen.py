# --- user input is embedded safely -----------------------------------------------


@pytest.mark.parametrize(
    "text",
    [
        'Hallo "Welt"',
        "\"); import os; os.system('rm -rf /') #",
        "Zeile 1\nZeile 2\tTab",
        "Backslash \\ am Ende \\",
        "Ümlaute äöü ß – ∑ 🙂",
        "\x00\x1b[31m",
        "'''\"\"\"",
    ],
)
def test_text_is_embedded_as_exact_string_literal(text: str) -> None:
    obj = make_object(ObjectKind.TEXT, "T", "t", text=text)
    tree = ast.parse(script_for(scene_with(obj)))
    calls = [node for node in ast.walk(tree) if isinstance(node, ast.Call) and getattr(node.func, "id", "") == "Text"]
    assert len(calls) == 1
    literal = calls[0].args[0]
    assert isinstance(literal, ast.Constant)
    assert literal.value == text


@pytest.mark.parametrize("latex", [r"\int_0^1 x^2\,dx", 'a "quoted" b', "ends with \\", "a\nb"])
def test_latex_is_embedded_as_exact_string_literal(latex: str) -> None:
    obj = make_object(ObjectKind.MATH_TEX, "F", "f", latex=latex)
    tree = ast.parse(script_for(scene_with(obj)))
    calls = [node for node in ast.walk(tree) if isinstance(node, ast.Call) and getattr(node.func, "id", "") == "MathTex"]
    assert calls[0].args[0].value == latex


